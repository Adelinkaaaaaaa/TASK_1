#
# Q2. Восстановление архива ООО «Рога и Копыта».
#
# Запуск (из папки репозитория):
#     bash restore_archive.sh
#
# Скрипт создаёт папку archive в репозитории. При повторном запуске
# архив пересоздаётся точно таким же.
#
# Подглядывать сюда — не спортивно. Кодовое слово ищи в архиве с помощью grep :)

set -u

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ARCHIVE_DIR="$REPO_DIR/archive"

# ---------------------------------------------------------------------------
# Кодовое слово: у каждого участника своё, оно зависит от почты в git config
# ---------------------------------------------------------------------------

# Важно: слова-ловушки ниже по тексту (KAKTUS, ARBUZ, PINGVIN, RAKETA, MAYAK, SAMOVAR,
# BUBLIK, KLUBNIKA) не должны встречаться в этом списке.
WORDS=(ANANAS BARABAN VERBLYUD GAMAK ZHIRAF ZONTIK ZVEZDA KOMPAS LIMONAD KOMBAYN
       NOSOROG OBLAKO PODSOLNUH TRAKTOR SNEGIR TELESKOP UTYUG FONAR CHEMODAN SHOKOLAD
       YABLOKO KENGURU BALALAYKA MATRESHKA KARANDASH VELOSIPED BEGEMOT VOLCHOK DELFIN KOSMONAVT)

email="$(git -C "$REPO_DIR" config user.email 2>/dev/null)"
if [ -z "$email" ]; then
    echo "Ошибка: Git не знает твою почту."
    echo "Вернись к заданию Q0 (шаг 5), настрой user.email и запусти скрипт снова."
    exit 1
fi
email="$(printf '%s' "$email" | tr '[:upper:]' '[:lower:]')"

sum=0
for ((i = 0; i < ${#email}; i++)); do
    printf -v code '%d' "'${email:i:1}"
    sum=$((sum + code))
done
SECRET="${WORDS[sum % ${#WORDS[@]}]}"

# ---------------------------------------------------------------------------

count=0
write() {  # $1 путь внутри архива, $2 содержимое
    mkdir -p "$ARCHIVE_DIR/$(dirname "$1")"
    printf '%s' "$2" > "$ARCHIVE_DIR/$1"
    count=$((count + 1))
}

echo "Восстанавливаю архив ООО «Рога и Копыта»..."
rm -rf "$ARCHIVE_DIR"

